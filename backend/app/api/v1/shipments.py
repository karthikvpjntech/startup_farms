@router.post(
    "/farmer/shipments",
    response_model=ShipmentResponse,
    status_code=status.HTTP_201_CREATED,
    summary="Farmer Creates Shipment & Packaging",
)
def create_farmer_shipment(
    data: ShipmentCreate,
    current_user: User = Depends(require_roles(RoleEnum.FARMER, RoleEnum.SUPER_ADMIN)),
    db: Session = Depends(get_db),
):
    """
    Farmer creates a shipment for a confirmed marketplace order with weight, packaging,
    and automatic Barcode/QR generation + optional transport pickup scheduling.
    """
    profile = get_farmer_profile(current_user, db)
    service = ShipmentService(db)
    return service.create_shipment(
        farmer_profile_id=profile.id,
        user_id=current_user.id,
        data=data
    )


@router.get(
    "/farmer/shipments",
    summary="List Farmer's Shipments",
)
def list_farmer_shipments(
    page: int = Query(default=1, ge=1),
    page_size: int = Query(default=20, ge=1, le=100),
    status: Optional[str] = Query(default=None),
    search: Optional[str] = Query(default=None),
    current_user: User = Depends(require_roles(RoleEnum.FARMER, RoleEnum.SUPER_ADMIN)),
    db: Session = Depends(get_db),
):
    """
    Returns paginated list of shipments generated by the logged-in farmer.
    """
    profile = get_farmer_profile(current_user, db)
    service = ShipmentService(db)
    items, total = service.list_farmer_shipments(
        farmer_profile_id=profile.id,
        page=page,
        page_size=page_size,
        status=status,
        search=search,
    )
    return {
        "items": [ShipmentResponse.model_validate(s) for s in items],
        "total": total,
        "page": page,
        "page_size": page_size,
        "total_pages": (total + page_size - 1) // page_size if total > 0 else 1,
    }


@router.get(
    "/farmer/shipments/{shipment_id}",
    response_model=ShipmentResponse,
    summary="Get Farmer Shipment Details",
)
def get_farmer_shipment_details(
    shipment_id: uuid.UUID,
    current_user: User = Depends(require_roles(RoleEnum.FARMER, RoleEnum.SUPER_ADMIN)),
    db: Session = Depends(get_db),
):
    service = ShipmentService(db)
    shipment = service.get_shipment_by_id(shipment_id)
    profile = get_farmer_profile(current_user, db)
    if shipment.farmer_profile_id != profile.id and not any(r.role.name == "SUPER_ADMIN" for r in current_user.user_roles):
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail="Access denied.")
    return shipment


