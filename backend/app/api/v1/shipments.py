@router.get(
    "/driver/shipments/scan/{code}",
    summary="Universal Barcode/QR Code Scanner Resolution",
)
def scan_shipment_code(
    code: str,
    current_user: User = Depends(require_roles(RoleEnum.DRIVER, RoleEnum.SUPER_ADMIN)),
    db: Session = Depends(get_db),
):
    """
    Scans any scannable identifier (Tracking #, Shipment #, Package Barcode, or Pickup Code)
    and resolves the matching shipment and package information.
    """
    service = ShipmentService(db)
    result = service.scan_code(code)
    shipment = result["shipment"]
    return {
        "match_type": result["match_type"],
        "shipment": ShipmentResponse.model_validate(shipment) if shipment else None,
        "pickup": PickupRequestResponse.model_validate(result["pickup"]) if "pickup" in result else None,
    }


