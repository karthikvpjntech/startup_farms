from fastapi import APIRouter, Depends, Query, HTTPException, status
from sqlalchemy.orm import Session

from app.core.database import get_db
from app.dependencies.auth import get_current_user
from app.dependencies.authorization import require_roles
from app.models.enums import RoleEnum
from app.models.user import User
from app.models.farmer_profile import FarmerProfile
from app.schemas.shipment import (
    ShipmentCreate,
    ShipmentResponse,
    PublicTrackingResponse,
    PickupRequestCreate,
    PickupRequestResponse,
    ShipmentStatusUpdate,
    DeliveryAttemptCreate,
)
from app.services.shipment_service import ShipmentService

router = APIRouter(tags=["Shipments & Logistics Tracking"])


# Helper to get or create farmer profile
def get_farmer_profile(current_user: User, db: Session) -> FarmerProfile:
    profile = db.query(FarmerProfile).filter(FarmerProfile.user_id == current_user.id).first()
    if not profile:
        profile = FarmerProfile(user_id=current_user.id)
        db.add(profile)
        db.commit()
        db.refresh(profile)
    return profile


